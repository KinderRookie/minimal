#!/usr/bin/env node
/**
 * MINIMAL components build — zero dependency.
 *
 * Concatenates components/*.css in ORDER into:
 *   dist/components.css   components only (needs tokens.css first)
 *   dist/minimal.css      tokens + components, one import
 *
 * Guardrails (fail the build):
 *   - raw colors (hex / rgb() / hsl() / oklch() / named colors other than
 *     transparent & currentColor) outside comments — components consume --mn-* only
 *   - box-shadow / border-radius with literal values — the grammar has no shadows,
 *     and radius only comes from --mn-radius-* so the soft dialect can switch it
 */
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "components");
const DIST = join(ROOT, "dist");

/** Cascade order. _base first; frame before the blocks that sit inside it. Keep in sync with components/. */
const ORDER = [
  "_base",
  "type",
  "frame",
  "shell",
  "nav",
  "button",
  "choice",
  "param",
  "field",
  "form",
  "card",
  "table",
  "cells",
  "plot",
  "feedback",
  "list", // after feedback: extends .mn-menu (rich rows, danger item, dropdown)
  "chat",
];

const onDisk = readdirSync(SRC).filter((f) => f.endsWith(".css")).map((f) => f.slice(0, -4));
const missing = onDisk.filter((f) => !ORDER.includes(f));
const absent = ORDER.filter((f) => !onDisk.includes(f));
if (missing.length || absent.length) {
  console.error(`ORDER out of sync — not listed: [${missing}] · listed but missing: [${absent}]`);
  process.exit(1);
}

const stripComments = (s) => s.replace(/\/\*[\s\S]*?\*\//g, "");
const RULES = [
  [/#[0-9a-f]{3,8}\b/gi, "raw hex color"],
  [/\b(rgba?|hsla?|oklch|oklab|lab|lch)\(/gi, "raw color function"],
  [/:\s*(black|white|red|blue|gray|grey|orange)\b/gi, "named color"],
  [/box-shadow\s*:(?!\s*(?:none|var\())/gi, "box-shadow (the grammar has no shadows)"],
  [/border(?:-[a-z]+)*-radius\s*:(?!\s*(?:var\(|0\b|inherit|50%))/gi, "literal border-radius (use --mn-radius-*)"],
];

let errors = 0;
const guard = (name, text) => {
  const code = stripComments(text);
  for (const [re, what] of RULES) {
    for (const m of code.matchAll(re)) {
      const line = code.slice(0, m.index).split("\n").length;
      console.error(`  ${name}.css ~line ${line}: ${what} → "${m[0]}"`);
      errors++;
    }
  }
};
const chunks = ORDER.map((name) => {
  const text = readFileSync(join(SRC, `${name}.css`), "utf8");
  guard(name, text);
  return `/* ---- ${name}.css ---- */\n${text.trim()}\n`;
});

if (errors) {
  console.error(`components: ${errors} guardrail violation(s)`);
  process.exit(1);
}

const { version } = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8"));
const banner = `/*! MINIMAL components v${version} — AUTO-GENERATED by scripts/build-components.mjs from components/*.css */\n`;
const components = banner + chunks.join("\n");
const tokens = readFileSync(join(DIST, "tokens.css"), "utf8");

mkdirSync(DIST, { recursive: true });
writeFileSync(join(DIST, "components.css"), components);
writeFileSync(
  join(DIST, "minimal.css"),
  `/*! MINIMAL v${version} — tokens + components bundle */\n${tokens}\n${components}`
);
console.log(`components: ${ORDER.length} files → dist/components.css, dist/minimal.css`);
