#!/usr/bin/env node
/**
 * MINIMAL token build — zero dependency.
 *
 * Reads tokens/tokens.json and emits:
 *   dist/tokens.css            CSS custom properties (--mn-*)
 *   dist/tokens.resolved.json  fully resolved hex maps per theme × signal × paper (for checks / non-CSS tools)
 *   dist/tokens.js             ESM export of the resolved maps
 *
 * Cascade emitted into tokens.css (order matters — see DESIGN.md "Theming"):
 *   :root                               primitives + semantic.base + semantic.light
 *   :root,[data-theme],[data-signal]…   semantic.derived (recomputed per scope)
 *   [data-theme="dark"]                 semantic.dark
 *   [data-paper="warm"]                 paper variant (light only)
 *   @media (prefers-color-scheme: dark) semantic.dark unless data-theme="light"
 *   [data-signal="…"]                   signal variants, light then dark
 *   [data-diff="hue"]                   diff tint opt-in (only takes effect where the signal allows it)
 *   [data-dialect="soft"]               dialect variant
 *
 * Usage: node scripts/build-tokens.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIST = join(ROOT, "dist");
const P = "mn";

const src = JSON.parse(readFileSync(join(ROOT, "tokens", "tokens.json"), "utf8"));
const { version } = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8"));

/** Yield [path[], node] for every token node (has $value). */
function* walk(node, path = []) {
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith("$") || !v || typeof v !== "object") continue;
    if ("$value" in v) yield [[...path, k], v];
    else yield* walk(v, [...path, k]);
  }
}
const flat = (node) => new Map([...walk(node)].map(([p, t]) => [p.join("."), t.$value]));

const kebab = (s) => String(s).replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
const varName = (dotted) => `--${P}-` + dotted.split(".").map(kebab).join("-");

const primitive = flat(src.primitive);
const base = flat(src.semantic.base);
const light = flat(src.semantic.light);
const dark = flat(src.semantic.dark);
const derived = flat(src.semantic.derived);

const REF = /\{([^}]+)\}/g;

/** CSS value: every {ref} becomes var(--mn-…); arrays join as font stacks. */
function css(value) {
  if (Array.isArray(value)) return value.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(", ");
  if (typeof value !== "string") return String(value);
  return value.replace(REF, (_, ref) => {
    if (!primitive.has(ref) && !isSemantic(ref)) throw new Error(`Unknown token reference {${ref}}`);
    return `var(${varName(ref)})`;
  });
}
const isSemantic = (ref) => base.has(ref) || light.has(ref) || derived.has(ref);

/** Resolve a value to a literal inside a semantic scope map (for checks). */
function resolve(value, scope, seen = new Set()) {
  if (Array.isArray(value)) return value.join(", ");
  if (typeof value !== "string") return value;
  const whole = value.match(/^\{([^}]+)\}$/);
  if (!whole) return value; // literals and color-mix strings stay as-is
  const ref = whole[1];
  if (seen.has(ref)) throw new Error(`Circular token reference {${ref}}`);
  const next = primitive.has(ref) ? primitive.get(ref) : scope.get(ref);
  if (next === undefined) throw new Error(`Unknown token reference {${ref}}`);
  return resolve(next, scope, new Set(seen).add(ref));
}

const decls = (map, indent = "  ") =>
  [...map].map(([k, v]) => `${indent}${varName(k)}: ${css(v)};`).join("\n");
const block = (selector, map) => `${selector} {\n${decls(map)}\n}`;

// --- Variants --------------------------------------------------------------------------
const signals = Object.entries(src.variant.signal).map(([name, v]) => ({
  name,
  light: flat(v.light),
  dark: flat(v.dark),
}));
const warm = flat(src.variant.paper.warm.light);
const soft = flat(src.variant.dialect.soft.base);
const diffHue = flat(src.variant.diff.hue.base);

const OS_DARK = ':root:not([data-theme="light"])';

const parts = [
  `/*! MINIMAL tokens v${version} — AUTO-GENERATED by scripts/build-tokens.mjs. Do not edit by hand. */`,
  `:root {\n  --${P}-version: "${version}";\n\n  /* primitives */\n${decls(primitive)}\n\n  /* semantic · base */\n${decls(base)}\n\n  /* semantic · light (default) */\n${decls(light)}\n}`,
  `/* derived — recomputed in every scope that can change signal, paper or theme */`,
  block(":root,\n[data-theme],\n[data-signal],\n[data-paper],\n[data-diff]", derived),
  block('[data-theme="dark"]', dark),
  `/* warm paper — light only */`,
  block('[data-paper="warm"]:not([data-theme="dark"])', warm),
  `@media (prefers-color-scheme: dark) {\n${block(OS_DARK, dark).replace(/^/gm, "  ")}\n}`,
  ...signals.flatMap((s) => [
    block(`[data-signal="${s.name}"]`, s.light),
    block(`[data-theme="dark"][data-signal="${s.name}"],\n[data-theme="dark"] [data-signal="${s.name}"]`, s.dark),
    `@media (prefers-color-scheme: dark) {\n${block(
      `${OS_DARK}[data-signal="${s.name}"],\n${OS_DARK} [data-signal="${s.name}"]`,
      s.dark
    ).replace(/^/gm, "  ")}\n}`,
  ]),
  block('[data-diff="hue"]', diffHue),
  block('[data-dialect="soft"]', soft),
  "",
];

mkdirSync(DIST, { recursive: true });
writeFileSync(join(DIST, "tokens.css"), parts.join("\n\n"));

// --- Resolved maps (theme × paper × signal) ---------------------------------------------
const merge = (...maps) => new Map(maps.flatMap((m) => [...m]));
const resolveAll = (scope) =>
  Object.fromEntries([...scope].map(([k, v]) => [k.split(".").map(kebab).join("-"), resolve(v, scope)]));

const resolved = {};
for (const theme of ["light", "dark"]) {
  for (const paper of theme === "light" ? ["white", "warm"] : ["white"]) {
    for (const signal of ["red", ...signals.map((s) => s.name)]) {
      const sig = signals.find((s) => s.name === signal);
      const scope = merge(
        base,
        theme === "light" ? light : dark,
        paper === "warm" ? warm : new Map(),
        sig ? sig[theme] : new Map()
      );
      resolved[`${theme}/${paper}/${signal}`] = resolveAll(scope);
    }
  }
}
writeFileSync(join(DIST, "tokens.resolved.json"), JSON.stringify(resolved, null, 2) + "\n");
writeFileSync(
  join(DIST, "tokens.js"),
  `// AUTO-GENERATED by scripts/build-tokens.mjs\nexport const version = ${JSON.stringify(version)};\n` +
    `export const fonts = ${JSON.stringify({ mono: css(primitive.get("font.family.mono")), sans: css(primitive.get("font.family.sans")) }, null, 2)};\n` +
    `export const tokens = ${JSON.stringify(resolved, null, 2)};\n`
);

console.log(`tokens: ${primitive.size} primitives, ${light.size + base.size + derived.size} semantic roles, ${Object.keys(resolved).length} resolved scopes → dist/`);
